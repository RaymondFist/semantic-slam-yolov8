#!/usr/bin/env bash
# =============================================================================
# autodl_prepare_data.sh - fill in the input data needed by P1/P2 (AutoDL cloud platform)
#
# The current autodl data/ holds only "result data" (GT/trajectories/detections/JSON); the re-runnable inputs
# are missing: TUM sequences not extracted, no associate.txt, no datasets_masked. This script fills them in.
#
# Steps:
#   1. Extract data/datasets/TUM/*.tgz to restore rgb/, depth/, rgb.txt, depth.txt
#   2. Generate associate.txt for each sequence with scripts/associate.py
#   3. Generate data/datasets_masked with scripts/mask_dataset.py --all (based on detections)
#
# Usage:  bash autodl_prepare_data.sh        # prepare TUM only (needed for P1)
#         bash autodl_prepare_data.sh --all # also KITTI/EuRoC (if already extracted)
#
# Output:
#   ${DATA_DIR}/datasets/TUM/rgbd_dataset_freiburg3_*/   (fully extracted sequences)
#   ${DATA_DIR}/datasets_masked/TUM/...                  (masked sequences, for P1 mask)
#   ${DATA_DIR}/datasets_randmask/...                    (random masks, for P2, generated by the main script)
# =============================================================================
set -u

# ------------------------------ Environment variables (overridable) ------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SEMANTIC_SLAM_ROOT="${SEMANTIC_SLAM_ROOT:-$SCRIPT_DIR}"
DATA_DIR="${DATA_DIR:-$SEMANTIC_SLAM_ROOT/data}"
DO_ALL=0
for a in "$@"; do [ "$a" = "--all" ] && DO_ALL=1; done

TUM_DIR="${DATA_DIR}/datasets/TUM"
mkdir -p "${TUM_DIR}"

echo "  SLAM_ROOT = ${SEMANTIC_SLAM_ROOT}"
echo "  DATA_DIR  = ${DATA_DIR}"

# 5 TUM sequences (match the paper/P1)
TUM_SEQS=(sitting_static sitting_xyz walking_static walking_xyz walking_halfsphere)

# =============================================================================
# Steps 1+2: extract tgz + generate associate.txt
# =============================================================================
echo ""
echo "[1/2] Extract TUM tgz files and generate associate.txt"
for seq in "${TUM_SEQS[@]}"; do
  seq_dir="${TUM_DIR}/rgbd_dataset_freiburg3_${seq}"
  if [ -d "${seq_dir}" ] && [ -f "${seq_dir}/associate.txt" ]; then
    echo "  ${seq}: ready (associate.txt exists), skipping"
    continue
  fi
  tgz="${TUM_DIR}/rgbd_dataset_freiburg3_${seq}.tgz"
  if [ ! -f "${tgz}" ]; then
    echo "  [WARN] ${seq}: neither an extracted directory nor a .tgz exists, skipping"
    continue
  fi
  echo "  Extracting ${seq}.tgz ..."
  ( cd "${TUM_DIR}" && tar -xzf "${tgz}" )
  if [ -f "${seq_dir}/rgb.txt" ] && [ -f "${seq_dir}/depth.txt" ]; then
    ( cd "${seq_dir}" && python3 "${SEMANTIC_SLAM_ROOT}/scripts/associate.py" rgb.txt depth.txt > associate.txt )
    echo "  ${seq}: associate.txt generated ($(wc -l < "${seq_dir}/associate.txt") lines)"
  else
    echo "  [WARN] ${seq}: rgb.txt/depth.txt missing after extraction, check the .tgz contents"
  fi
done

# =============================================================================
# Step 3: generate masked data datasets_masked
# =============================================================================
echo ""
echo "[2/2] Generate masked data (mask_dataset.py --all -> datasets_masked)"
if [ -d "${DATA_DIR}/datasets" ] && [ -d "${DATA_DIR}/detections" ]; then
  python3 "${SEMANTIC_SLAM_ROOT}/scripts/mask_dataset.py" \
      --all \
      --datasets "${DATA_DIR}/datasets" \
      --detections-root "${DATA_DIR}/detections" \
  || echo "  [WARN] mask generation failed, see output above"
  echo "  Masked data output directory: ${DATA_DIR}/datasets_masked/"
  ls -d ${DATA_DIR}/datasets_masked/TUM/*/ 2>/dev/null || echo "  (no masked sequences generated)"
else
  echo "  [WARN] datasets or detections missing, cannot generate masks"
fi

echo ""
echo "===== Data preparation complete ====="
echo "  Verify P1 inputs:"
for seq in "${TUM_SEQS[@]}"; do
  echo "  - raw   ${DATA_DIR}/datasets/TUM/rgbd_dataset_freiburg3_${seq}/associate.txt : $([ -f "${DATA_DIR}/datasets/TUM/rgbd_dataset_freiburg3_${seq}/associate.txt" ] && echo OK || echo 'missing')"
  echo "  - mask  ${DATA_DIR}/datasets_masked/TUM/rgbd_dataset_freiburg3_${seq}          : $([ -d "${DATA_DIR}/datasets_masked/TUM/rgbd_dataset_freiburg3_${seq}" ] && echo OK || echo 'missing')"
done
echo ""
echo "Then run:  ./autodl_p1p2.sh 5"